#ifndef BONGOCAT_ASSETS_MACROS_IMAGE_H
#define BONGOCAT_ASSETS_MACROS_IMAGE_H

#include <stdint.h>
#include <stddef.h>

/// Section placement for embedded assets and config data.

#if defined(__GNUC__) || defined(__clang__)
#  define BONGOCAT_SECTION(name) __attribute__((section(name)))
#else
#  define BONGOCAT_SECTION(name)
#endif

#define BONGOCAT_ASSETS_STRINGIFY_IMPL(x) #x
#define BONGOCAT_ASSETS_STRINGIFY(x) BONGOCAT_ASSETS_STRINGIFY_IMPL(x)

// -----------------------------------------------------------------------------
// hard-coded per-set sections: USE THESE in the asset sources (one set per file)
// ".assets.<set>.<kind>", the linker script groups them per set (_bongocat_start/stop_assets_<set>)
// -----------------------------------------------------------------------------
#define BONGOCAT_ASSETS_SET_SECTION(set, kind) BONGOCAT_SECTION(".assets." #set "." kind)

/// @NOTE(assets): 0. add the set sections (and the set to BONGOCAT_ASSET_SETS in cmake/EmbeddedAssets.cmake)

/// per-set boundaries inside .bongocat.assets, generated by bongocat_target_assets_segment() (cmake/EmbeddedAssets.cmake)
/// only for the sets linked into the executable; declared WEAK, so they are null (empty range) for sets that are not
/// linked, no PROVIDE() needed in the linker script.
/// Use at global scope (outside any namespace): BONGOCAT_ASSETS_DECLARE_SET_RANGE(dm);
#if defined(__GNUC__) || defined(__clang__)
#  define BONGOCAT_WEAK __attribute__((weak))
#else
#  define BONGOCAT_WEAK
#endif
#ifdef __cplusplus
#  define BONGOCAT_ASSETS_EXTERN_C extern "C"
#else
#  define BONGOCAT_ASSETS_EXTERN_C extern
#endif
#define BONGOCAT_ASSETS_DECLARE_SET_RANGE(set)                                       \
  BONGOCAT_ASSETS_EXTERN_C const char _bongocat_start_assets_##set[] BONGOCAT_WEAK; \
  BONGOCAT_ASSETS_EXTERN_C const char _bongocat_stop_assets_##set[] BONGOCAT_WEAK

// =============================================================================
// config load/reload block (.config)
// =============================================================================

#define CONFIG_STRING_SECTION BONGOCAT_SECTION(".config.str")

#endif  // BONGOCAT_ASSETS_MACROS_IMAGE_H
